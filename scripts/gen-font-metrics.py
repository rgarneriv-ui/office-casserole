#!/usr/bin/env python3
"""Regenerates engines/pdf-engine/src/helvetica-metrics.ts from reportlab's
verified base-14 AFM data. Run from the repo root: python3 scripts/gen-font-metrics.py"""
from reportlab.pdfbase.pdfmetrics import getFont
import json
fonts = {
  "helvetica": "Helvetica",
  "helveticaBold": "Helvetica-Bold",
  "helveticaOblique": "Helvetica-Oblique",
  "helveticaBoldOblique": "Helvetica-BoldOblique",
}
out = {}
for key, name in fonts.items():
    widths = getFont(name).widths
    out[key] = [widths[i] if i < len(widths) and widths[i] else 0 for i in range(32, 256)]
body = "// GENERATED by scripts/gen-font-metrics.py from reportlab's verified\n"
body += "// base-14 AFM data. Widths in units/1000 em, indexed from char code 32.\n"
body += "// Do not edit by hand; regenerate instead.\n"
body += "export const FONT_WIDTHS: Record<string, number[]> = " + json.dumps(out) + ";\n"
body += "export const FIRST_CHAR = 32;\n"
open("engines/pdf-engine/src/helvetica-metrics.ts", "w").write(body)
print("written")
